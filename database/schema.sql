CREATE TABLE PATIENT_TEST_RECORDS (
    PATIENT_ID   VARCHAR2(20)   NOT NULL,
    PATIENT_NAME VARCHAR2(100)  NOT NULL,
    AGE          NUMBER(3)      NOT NULL,
    GENDER       VARCHAR2(10)   NOT NULL,
    TEST_NAME    VARCHAR2(100)  NOT NULL,
    TEST_RESULT  VARCHAR2(2000) NOT NULL,
    CONSTRAINT PK_PATIENT_TEST_RECORDS PRIMARY KEY (PATIENT_ID),
    CONSTRAINT CK_PATIENT_TEST_AGE CHECK (AGE BETWEEN 0 AND 120),
    CONSTRAINT CK_PATIENT_TEST_GENDER CHECK (GENDER IN ('Female', 'Male', 'Other'))
);
